#ifndef PROTOCOL_H
#define PROTOCOL_H

#include <stdint.h>

// Packed structures to ensure no compiler padding ruins the byte counts
#pragma pack(push, 1)

/**
 * Election Packet (40 Bytes)
 */
typedef struct {
    uint32_t score;           // 4 Bytes: Score metric for better leader choice
    uint16_t origin_id;       // 2 Bytes: ID of the node owning the score
    uint16_t sender_id;       // 2 Bytes: ID of the neighbour forwarding the packet
    uint8_t score_hmac[16];   // 16 Bytes: HMAC of Score generated by origin node
    uint8_t origin_hmac[16];  // 16 Bytes: HMAC of Origin ID generated by origin node
} ElectionPacket_t;

/**
 * Leader Heartbeat (38 Bytes + 2 Bytes Padding = 40 Bytes)
 */
typedef struct {
    uint32_t counter;         // 4 Bytes: Incremental counter to ensure packet freshness
    uint16_t leader_id;       // 2 Bytes: ID of the network leader
    uint8_t counter_hmac[16]; // 16 Bytes: HMAC of Counter generated by leader node
    uint8_t leader_hmac[16];  // 16 Bytes: HMAC of Leader ID generated by leader node
    uint8_t padding[2];       // 2 Bytes: Padding to align packet sizes
} LeaderHeartbeat_t;

/**
 * Presence Heartbeat Packet (6 Bytes)
 */
typedef struct {
    uint16_t node_id;         // 2 Bytes: ID of the broadcasting node
    uint16_t leader_id;       // 2 Bytes: ID of the leader of the broadcasting node's network
    uint16_t sequence;        // 2 Bytes: Monotonically increasing counter (discard stale)
} PresenceHeartbeat_t;

#pragma pack(pop)

// Packet Types
typedef enum {
    PACKET_TYPE_ELECTION = 0x01,
    PACKET_TYPE_LEADER_HB = 0x02,
    PACKET_TYPE_PRESENCE_HB = 0x03
} PacketType_t;

// Utility functions for packet manipulation
void protocol_build_presence_hb(PresenceHeartbeat_t* hb, uint16_t node_id, uint16_t leader_id, uint16_t seq);
void protocol_build_election(ElectionPacket_t* ep, uint32_t score, uint16_t origin, uint16_t sender, const uint8_t* score_hmac, const uint8_t* origin_hmac);
void protocol_build_leader_hb(LeaderHeartbeat_t* lhb, uint32_t counter, uint16_t leader_id, const uint8_t* counter_hmac, const uint8_t* leader_hmac);

#endif // PROTOCOL_H

